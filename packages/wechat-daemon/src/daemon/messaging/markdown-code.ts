/**
 * Markdown 代码区域的遮罩。
 *
 * 出站媒体语法（`![](路径)` / `[附件](file:///…)`）只在**正文**里算数：agent 经常会在回答里
 * 用行内代码或代码围栏「教用户怎么写」，那些是示例，不能真去读盘/下载。
 * 2026-11-17 真机撞到过：worker 回了一句「图片直接写 `![](路径)` 就行」，结果 daemon 真去
 * 解析了字面量「路径」，用户收到的答复后面多出一条「有 1 张图片没能下载下来」。
 *
 * 做法：把代码区域替换成**等长空格**（保留换行），这样在原串与遮罩串上算出的下标一致，
 * 调用方可以「在遮罩串上匹配、回到原串上切除」。
 */

/** 围栏代码块：``` 或 ~~~ 成对出现；没有收尾围栏时一直遮到文末（半截围栏也不该让后面的示例生效）。 */
const CODE_FENCE = /(^|\n)[ \t]*(`{3,}|~{3,})[\s\S]*?(?:\n[ \t]*\2[ \t]*(?=\n|$)|$)/g;

/** 行内代码：同长度的反引号成对；不跨行（跨行多半是散落的单个反引号，遮掉会误伤正文）。 */
const INLINE_CODE = /(`+)[^\n]*?\1/g;

const blank = (s: string): string => s.replace(/[^\n]/g, " ");

/** 把 Markdown 代码围栏与行内代码替换成等长空白；其余字符原样保留（下标不变）。 */
export function maskCodeRegions(text: string): string {
  return text.replace(CODE_FENCE, blank).replace(INLINE_CODE, blank);
}
